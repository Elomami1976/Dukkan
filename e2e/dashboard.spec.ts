import { test, expect, type Page } from '@playwright/test'

async function seed(page: Page) {
  await page.goto('/')
  await page.evaluate(async () => {
    // Isolated browser context only. These records never enter a user's desktop database or production bundle.
    const { useAppStore } = await import('/src/store.ts')
    const s = useAppStore.getState()
    await s.completeSetup({ name: 'متجر الاختبار المحلي', type: 'مواد غذائية', phone: '', address: '', taxNumber: '', logo: '', primaryColor: '#2563eb', currency: 'الدينار الليبي' }, { name: 'مدير الاختبار', username: 'test-admin', password: 'local-test-only-123' })
    await s.addCustomer({ name: 'عميل الاختبار', phone: '', city: '' })
    await s.addSupplier({ name: 'مورد الاختبار', phone: '', city: '' })
    await s.addProduct({ name: 'قهوة عربية', category: 'مواد غذائية', unit: 'عبوة', cost: 1000, price: 3000, wholesalePrice: 2500, stock: 8, minStock: 3, trackInventory: true, status: 'active' })
    const product = useAppStore.getState().products[0], customer = useAppStore.getState().customers[0]
    await s.completeSale([{ productId: product.id, qty: 6 }], 10000, customer.id, 'نقدي', 0)
    await s.addExpense({ category: 'نقل', note: 'مصروف اختبار', amount: 1000 })
  })
  await expect(page.locator('.dashboard-kpis')).toBeVisible()
}
test('RTL dashboard, filters, customization, real actions, and offline usage', async ({ page, context }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await seed(page)
  await expect(page.locator('.intelligent-dashboard')).toHaveAttribute('dir', 'rtl')
  await expect(page.locator('.kpi-widget').nth(0)).toContainText('18.000')
  await expect(page.locator('.kpi-widget').nth(1)).toContainText('12.000')
  await page.getByRole('button', { name: 'متقدم', exact: true }).click()
  await expect(page.locator('.widget-profitability')).toContainText('11.000')
  await expect(page.locator('.widget-priorities')).toContainText('1 منتجات عند الحد الأدنى')
  await page.getByLabel('فترة التقرير').selectOption('yesterday')
  await expect(page.locator('.kpi-widget').nth(0)).toContainText('0.000')
  await expect(page.locator('.kpi-widget').nth(2)).toContainText('8.000')
  await page.getByLabel('فترة التقرير').selectOption('today')
  await page.getByRole('button', { name: 'تخصيص', exact: true }).click()
  await page.getByLabel('قالب النشاط').selectOption('grocery')
  await page.locator('.widget-order').getByLabel('توزيع المصروفات', { exact: true }).uncheck()
  await expect(page.locator('.widget-expenses')).toHaveCount(0)
  await page.getByRole('button', { name: 'تخصيص', exact: true }).click()
  await context.setOffline(true)
  await page.getByLabel('فترة التقرير').selectOption('week')
  await expect(page.locator('.kpi-widget').first()).toContainText('18.000')
  await page.screenshot({ path: 'docs/assets/dashboard-glass-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 1024, height: 768 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.widget-priorities .business-alert').first().getByRole('button').click()
  await expect(page.getByRole('heading', { name: 'المخزون', exact: true })).toBeVisible()
  expect(failures).toEqual([])
})
test('empty state, no external requests, and reduced motion', async ({ page }) => {
  const external: string[] = []
  page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:1420')) external.push(request.url()) })
  await seed(page)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByLabel('فترة التقرير').selectOption('yesterday')
  await expect(page.locator('.widget-sales')).toContainText('لا توجد مبيعات')
  expect(external).toEqual([])
})
test('preferences survive reload and cashier cannot open analytics', async ({ page }) => {
  await seed(page)
  await page.getByRole('button', { name: 'متقدم', exact: true }).click()
  await page.getByRole('button', { name: 'تخصيص', exact: true }).click()
  await page.locator('.widget-order').getByLabel('توزيع المصروفات', { exact: true }).uncheck()
  await page.reload()
  await page.evaluate(async () => { const { useAppStore } = await import('/src/store.ts'); await useAppStore.getState().login('test-admin','local-test-only-123') })
  await expect(page.getByRole('button', { name: 'متقدم', exact: true })).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('.widget-expenses')).toHaveCount(0)
  await page.evaluate(async () => {
    const { useAppStore } = await import('/src/store.ts'); const s = useAppStore.getState()
    await s.addUser('كاشير اختبار','cash-test','cash-test-only-123','cashier'); s.logout(); await s.login('cash-test','cash-test-only-123')
  })
  await expect(page.locator('.intelligent-dashboard')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'نقطة البيع', exact: true })).toBeVisible()
})
